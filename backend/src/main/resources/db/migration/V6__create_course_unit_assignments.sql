-- StudyMatch - Perfil Docente
-- V6: docentes e alunos associados às unidades curriculares
--
-- course_unit_teachers: o admin associa docentes às UCs (R2).
-- course_unit_students: o admin inscreve alunos nas UCs que estão
--   a frequentar (R1). Não substitui o histórico (enrollments).
--
-- Correr no Supabase depois do V5 e antes de arrancar o backend.
-- Reverter com U6__create_course_unit_assignments.sql.
-- =====================================================

BEGIN;

CREATE TABLE IF NOT EXISTS course_unit_teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_unit_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,

    CONSTRAINT fk_cut_course_unit
        FOREIGN KEY (course_unit_id) REFERENCES course_units(id) ON DELETE CASCADE,
    CONSTRAINT fk_cut_teacher
        FOREIGN KEY (teacher_id) REFERENCES app_users(id) ON DELETE CASCADE,
    CONSTRAINT uk_course_unit_teacher
        UNIQUE (course_unit_id, teacher_id)
);

CREATE TABLE IF NOT EXISTS course_unit_students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_unit_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,

    CONSTRAINT fk_cus_course_unit
        FOREIGN KEY (course_unit_id) REFERENCES course_units(id) ON DELETE CASCADE,
    CONSTRAINT fk_cus_student
        FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    -- Um aluno só pode estar inscrito uma vez na mesma UC.
    CONSTRAINT uk_course_unit_student
        UNIQUE (course_unit_id, student_id)
);

CREATE INDEX IF NOT EXISTS idx_cut_teacher ON course_unit_teachers(teacher_id);
CREATE INDEX IF NOT EXISTS idx_cus_student ON course_unit_students(student_id);

COMMIT;
