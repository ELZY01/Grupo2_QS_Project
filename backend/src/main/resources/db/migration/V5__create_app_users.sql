BEGIN;

CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    student_id BIGINT UNIQUE,

    CONSTRAINT fk_app_user_student
        FOREIGN KEY (student_id)
        REFERENCES students(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_app_user_role
        CHECK (role IN ('ADMIN', 'DOCENTE', 'ALUNO')),

    -- Só as contas de aluno estão ligadas a um estudante.
    CONSTRAINT chk_app_user_student
        CHECK ((role = 'ALUNO') = (student_id IS NOT NULL))
);

COMMIT;
