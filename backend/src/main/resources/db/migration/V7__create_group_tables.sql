
-- ============================================================
-- V4 - Criacao das tabelas de formacao automatica de grupos
-- Issue #68
-- ============================================================

-- 1. Contextos de formacao
CREATE TABLE group_contexts (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                name VARCHAR(255) NOT NULL,
                                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                generated_at TIMESTAMP
);

-- 2. Estudantes associados a cada contexto
CREATE TABLE group_context_students (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        context_id BIGINT NOT NULL,
                                        student_id BIGINT NOT NULL,

                                        CONSTRAINT fk_gcs_context
                                            FOREIGN KEY (context_id)
                                                REFERENCES group_contexts(id)
                                                ON DELETE CASCADE,

                                        CONSTRAINT fk_gcs_student
                                            FOREIGN KEY (student_id)
                                                REFERENCES students(id)
                                                ON DELETE CASCADE,

                                        CONSTRAINT uq_gcs_context_student
                                            UNIQUE (context_id, student_id)
);

-- 3. Grupos gerados
CREATE TABLE student_groups (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                context_id BIGINT NOT NULL,
                                generation_number INTEGER NOT NULL,
                                group_number INTEGER NOT NULL,
                                average DOUBLE PRECISION,
                                gap_to_others DOUBLE PRECISION,
                                generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT fk_sg_context
                                    FOREIGN KEY (context_id)
                                        REFERENCES group_contexts(id)
                                        ON DELETE CASCADE,

                                CONSTRAINT uq_sg_generation_group
                                    UNIQUE (context_id, generation_number, group_number),

    -- Necessario para validar a geracao dos membros.
                                CONSTRAINT uq_sg_context_generation_id
                                    UNIQUE (context_id, generation_number, id),

                                CONSTRAINT ck_sg_generation
                                    CHECK (generation_number > 0),

                                CONSTRAINT ck_sg_group_number
                                    CHECK (group_number > 0)
);

-- 4. Membros dos grupos
CREATE TABLE group_members (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               group_id BIGINT NOT NULL,
                               context_id BIGINT NOT NULL,
                               generation_number INTEGER NOT NULL,
                               student_id BIGINT NOT NULL,

    -- O grupo tem de pertencer ao mesmo contexto e geracao.
                               CONSTRAINT fk_gm_group_generation
                                   FOREIGN KEY (context_id, generation_number, group_id)
                                       REFERENCES student_groups(context_id, generation_number, id)
                                       ON DELETE CASCADE,

    -- O estudante tem de estar associado ao contexto.
                               CONSTRAINT fk_gm_context_student
                                   FOREIGN KEY (context_id, student_id)
                                       REFERENCES group_context_students(context_id, student_id)
                                       ON DELETE CASCADE,

    -- Um estudante so pode aparecer uma vez por grupo.
                               CONSTRAINT uq_gm_group_student
                                   UNIQUE (group_id, student_id),

    -- Um estudante so pode pertencer a um grupo por geracao.
                               CONSTRAINT uq_gm_student_generation
                                   UNIQUE (context_id, generation_number, student_id)
);

-- Indices para facilitar as consultas dos grupos e membros.
CREATE INDEX idx_sg_context_generation
    ON student_groups(context_id, generation_number);

CREATE INDEX idx_gm_group
    ON group_members(group_id);

CREATE INDEX idx_gm_student
    ON group_members(student_id);
