BEGIN;

-- 1. ESTUDANTES
CREATE TABLE IF NOT EXISTS students (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        student_number VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    course VARCHAR(255) NOT NULL,
    academic_year INTEGER NOT NULL,

    CONSTRAINT chk_student_academic_year
    CHECK (academic_year > 0)
    );

-- 2. UNIDADES CURRICULARES
CREATE TABLE IF NOT EXISTS course_units (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            code VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    ects INTEGER NOT NULL,
    academic_year INTEGER NOT NULL,
    semester INTEGER NOT NULL,

    CONSTRAINT chk_course_unit_ects
    CHECK (ects > 0),

    CONSTRAINT chk_course_unit_year
    CHECK (academic_year > 0),

    CONSTRAINT chk_course_unit_semester
    CHECK (semester IN (1, 2))
    );

-- 3. COMPETENCIAS
CREATE TABLE IF NOT EXISTS competencies (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            code VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    is_base BOOLEAN NOT NULL
    );

-- 4. INSCRICOES
CREATE TABLE IF NOT EXISTS enrollments (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           student_id BIGINT NOT NULL,
                                           course_unit_id BIGINT NOT NULL,
                                           school_year INTEGER NOT NULL,
                                           semester INTEGER NOT NULL,
                                           attempt_number INTEGER NOT NULL,
                                           grade INTEGER,
                                           status VARCHAR(255) NOT NULL,

    CONSTRAINT fk_enrollment_student
    FOREIGN KEY (student_id)
    REFERENCES students(id),

    CONSTRAINT fk_enrollment_course_unit
    FOREIGN KEY (course_unit_id)
    REFERENCES course_units(id),

    CONSTRAINT uk_enrollment_attempt
    UNIQUE (student_id, course_unit_id, attempt_number),

    CONSTRAINT chk_enrollment_grade
    CHECK (grade IS NULL OR grade BETWEEN 0 AND 20),

    CONSTRAINT chk_enrollment_attempt
    CHECK (attempt_number > 0),

    CONSTRAINT chk_enrollment_semester
    CHECK (semester IN (1, 2)),

    CONSTRAINT chk_enrollment_status
    CHECK (
              status IN ('EM_CURSO', 'APROVADO', 'REPROVADO')
    ),

    CONSTRAINT chk_enrollment_grade_status
    CHECK (
(status = 'EM_CURSO' AND grade IS NULL)
    OR
(status = 'APROVADO' AND grade BETWEEN 10 AND 20)
    OR
(status = 'REPROVADO' AND grade BETWEEN 0 AND 9)
    )
    );

-- 5. ASSOCIACOES ENTRE UC E COMPETENCIA
CREATE TABLE IF NOT EXISTS course_unit_competencies (
                                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                        course_unit_id BIGINT NOT NULL,
                                                        competency_id BIGINT NOT NULL,
                                                        weight DOUBLE PRECISION NOT NULL,

                                                        CONSTRAINT fk_cuc_course_unit
                                                        FOREIGN KEY (course_unit_id)
    REFERENCES course_units(id),

    CONSTRAINT fk_cuc_competency
    FOREIGN KEY (competency_id)
    REFERENCES competencies(id),

    CONSTRAINT uk_course_unit_competency
    UNIQUE (course_unit_id, competency_id),

    CONSTRAINT chk_competency_weight
    CHECK (weight > 0 AND weight <= 1)
    );

-- 6. QUIZZES
CREATE TABLE IF NOT EXISTS quizzes (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       version VARCHAR(255) NOT NULL UNIQUE
    );

-- 7. PERGUNTAS
CREATE TABLE IF NOT EXISTS questions (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         quiz_id BIGINT NOT NULL,
                                         competency_id BIGINT NOT NULL,
                                         text VARCHAR(1000) NOT NULL,
    question_order INTEGER NOT NULL,

    CONSTRAINT fk_question_quiz
    FOREIGN KEY (quiz_id)
    REFERENCES quizzes(id),

    CONSTRAINT fk_question_competency
    FOREIGN KEY (competency_id)
    REFERENCES competencies(id),

    CONSTRAINT uk_question_quiz_order
    UNIQUE (quiz_id, question_order),

    CONSTRAINT chk_question_order
    CHECK (question_order > 0)
    );

-- 8. SUBMISSOES DO QUIZ
CREATE TABLE IF NOT EXISTS quiz_submissions (
                                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                student_id BIGINT NOT NULL,
                                                quiz_id BIGINT NOT NULL,
                                                submitted_at TIMESTAMP(6) NOT NULL,

    CONSTRAINT fk_submission_student
    FOREIGN KEY (student_id)
    REFERENCES students(id),

    CONSTRAINT fk_submission_quiz
    FOREIGN KEY (quiz_id)
    REFERENCES quizzes(id)
    );

-- 9. RESPOSTAS
CREATE TABLE IF NOT EXISTS answers (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       submission_id BIGINT NOT NULL,
                                       question_id BIGINT NOT NULL,
                                       value INTEGER NOT NULL,

                                       CONSTRAINT fk_answer_submission
                                       FOREIGN KEY (submission_id)
    REFERENCES quiz_submissions(id),

    CONSTRAINT fk_answer_question
    FOREIGN KEY (question_id)
    REFERENCES questions(id),

    CONSTRAINT uk_answer_submission_question
    UNIQUE (submission_id, question_id),

    CONSTRAINT chk_answer_value
    CHECK (value BETWEEN 1 AND 5)
    );

COMMIT;
